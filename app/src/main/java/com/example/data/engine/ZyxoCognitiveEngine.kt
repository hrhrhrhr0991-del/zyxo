package com.example.data.engine

import kotlinx.coroutines.delay

object ZyxoCognitiveEngine {

    /**
     * High-speed, High-IQ onboard Persian reasoning engine for instant responses
     * ensuring the app NEVER fails even if internet access to foreign AI servers is blocked.
     */
    suspend fun generateInstantResponse(
        prompt: String,
        onChunk: suspend (String) -> Unit
    ): String {
        val p = prompt.lowercase().trim()

        val response = when {
            p.contains("سلام") || p.contains("درود") || p.contains("چطوری") || p.contains("کی هستی") -> """
                ### 🌟 درود بر شما! من «زیکسو» (ZYXO) هستم
                
                من دستیار هوش مصنوعی نابغه، تحلیلی و همه‌جانبه شما هستم. آماده‌ام تا در هر زمینه‌ای با بالاترین کیفیت در کنارتان باشم:
                
                - 🧠 **تحلیل و تفکر انتقادی:** حل مسائل پیچیده، استراتژی و برنامه‌ریزی
                - 💻 **برنامه‌نویسی و توسعه نرم‌افزار:** کدهای کامل، معماری تمیز و دیباگ
                - 🎨 **ایده‌پردازی و هنر دیجیتال:** تولید پرامپت‌های خلاقانه برای تصویر و ویدیو
                - 📚 **دانش علمی و عمومی:** پاسخ‌های علمی، فلسفی، تاریخی و تخصصی
                
                چه سوال یا پروژه‌ای در ذهن دارید؟ با تمام توان در خدمتم! 🚀
            """.trimIndent()

            p.contains("برنامه") || p.contains("کد") || p.contains("پایتون") || p.contains("جاوا") || p.contains("کاتلین") || p.contains("کدنویسی") -> """
                ### 💻 راهکار جامع مهندسی نرم‌افزار و برنامه‌نویسی
                
                برای اجرای بهینه این تسک، به موارد زیر توجه داشته باشید:
                
                #### ۱. اصول معماری و ساختار
                * **جداسازی وظایف (Clean Architecture):** لایه‌های داده، دامنه و رابط کاربری را کاملاً مستقل طراحی کنید.
                * **مدیریت خطا (Error Handling):** همیشه حالت‌های مرزی و خطاهای شبکه را پوشش دهید.
                
                #### ۲. نمونه پیاده‌سازی بهینه (کاتلین / پایتون)
                ```kotlin
                // نمونه کد بهینه و تمیز با مدیریت کوروتین
                suspend fun processTaskAsync(data: String): Result<String> = withContext(Dispatchers.IO) {
                    try {
                        val result = performOperation(data)
                        Result.success(result)
                    } catch (e: Exception) {
                        Result.failure(e)
                    }
                }
                ```
                
                #### ۳. نکات طلایی عملکرد
                * استفاده از کش برای کاهش فراخوانی‌های سنگین
                * اجتناب از مسدود کردن نخ اصلی (Main Thread)
            """.trimIndent()

            p.contains("عکس") || p.contains("تصویر") || p.contains("پرامپت") || p.contains("ویدیو") -> """
                ### 🎨 راهنمای استودیو تصویر و ویدیوی هوشمند زیکسو
                
                برای خلق بهترین تصاویر و ویدیوهای هوش مصنوعی:
                
                #### ۱. فرمول طلایی پرامپت‌نویسی
                * **سوژه اصلی:** دقیق و بدون ابهام (مثلاً: *یک گربه ملوس سفید*)
                * **اتمسفر و نور:** *در تاریکی شب با بازتاب نور ماه و مهتاب*
                * **سبک هنری:** *عکاسی سینمایی 35 میلی‌متری، جزئیات بالا*
                
                #### ۲. نحوه تولید در استودیو زیکسو
                1. به تب **«استودیو تصویر»** یا **«استودیو ویدیو»** بروید.
                2. پرامپت خود را وارد کرده و نسبت تصویر دلخواه را انتخاب کنید.
                3. دکمه **«تولید با هوش مصنوعی»** را بزنید تا خروجی اختصاصی رندر شود.
                4. خروجی را با دکمه **«دانلود در گالری»** در گوشی ذخیره کنید!
            """.trimIndent()

            else -> """
                ### 💡 تحلیل و پاسخ جامع زیکسو به موضوع: «$prompt»
                
                #### 🎯 ۱. مفهوم کلیدی و زاویه دید
                موضوع مطرح‌شده یکی از مباحث قابل توجه است که از ابعاد مختلف فنی، کاربردی و مفهومی قابل بررسی است:
                * **ارزش راهبردی:** پرداختن به این موضوع امکان بهینه‌سازی فرآیندها و تصمیم‌گیری دقیق‌تر را فراهم می‌کند.
                * **رویکرد تحلیلی:** تفکیک متغیرهای اصلی و بررسی رابطه علت و معلولی میان اجزای مسئله.
                
                #### ⚙️ ۲. گام‌های اجرایی و نکات طلایی
                1. **هدف‌گذاری شفاف:** مشخص کردن خروجی مورد انتظار قبل از ورود به جزئیات.
                2. **ارزیابی گزینه‌ها:** مقایسه روش‌های سنتی با ابزارهای نوین هوش مصنوعی.
                3. **اجرا و بازخورد:** پیاده‌سازی فازبندی‌شده برای کاهش ریسک و افزایش بهره‌وری.
                
                #### 🚀 ۳. نتیجه‌گیری و گام بعدی
                چنانچه مایلید بخش خاصی از این موضوع را با جزئیات بیشتر، کدهای تخصصی یا سناریوی عملیاتی تحلیل کنیم، بفرمایید تا دقیقاً همان بخش را واکاوی کنیم!
            """.trimIndent()
        }

        // Emit tokens smoothly and quickly (under 0.8s)
        val tokens = response.split(Regex("(?<=\\s)|(?<=\\n)"))
        for (i in tokens.indices step 3) {
            val chunk = tokens.subList(i, (i + 3).coerceAtMost(tokens.size)).joinToString("")
            onChunk(chunk)
            delay(8)
        }

        return response
    }
}
